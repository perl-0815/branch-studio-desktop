import type { AstNode, BehaviorTreeAst, CodeResult, Variable } from './types';

const quote = (s: string) =>
  JSON.stringify(s)
    .replace(/\u0085/g, '\\u0085')
    .replace(/\u2028/g, '\\u2028')
    .replace(/\u2029/g, '\\u2029');
const number = (n: unknown, fallback = 1) =>
  String(typeof n === 'number' && Number.isFinite(n) ? n : fallback);
const text = (n: unknown) => String(n ?? '');
function argumentsLiteral(value: unknown): string {
  const args: unknown = String(value ?? '').trim() ? JSON.parse(String(value)) : [];
  if (!Array.isArray(args)) throw new Error('Handler arguments must be a JSON array.');
  return `new object?[] { ${args
    .map((v) =>
      v === null
        ? 'null'
        : typeof v === 'string'
          ? quote(v)
          : typeof v === 'boolean'
            ? String(v).toLowerCase()
            : typeof v === 'number' && Number.isFinite(v)
              ? `${v}d`
              : (() => {
                  throw new Error('Only primitive handler arguments are supported.');
                })(),
    )
    .join(', ')} }`;
}
function literal(value: string, type: Variable['type']): string {
  if (type === 'string') return quote(value);
  if (type === 'Vector3')
    return `new global::System.Numerics.Vector3(${(JSON.parse(value) as number[]).map((n) => `${n}f`).join(', ')})`;
  if (type === 'float') return `${Number(value)}f`;
  return value;
}

/** Pure AST-to-source generation. Validation must succeed before calling this function. */
export function generateCSharp(ast: BehaviorTreeAst): CodeResult {
  const workflow = ast.mode === 'workflow';
  const runtime = `global::BranchStudio.${workflow ? 'Workflow' : 'Game'}`;
  const statusType = `global::BranchStudio.Contracts.${workflow ? 'WorkflowResult' : 'NodeStatus'}`;
  const variableType = (type: Variable['type']) =>
    type === 'Vector3' ? 'global::System.Numerics.Vector3' : type;
  const className = ast.settings.className;
  const handlerInterface = `I${className}Handlers`;
  const lines: string[] = [];
  const ranges: CodeResult['ranges'] = {};
  const handlers = new Map<string, boolean>();
  function collect(node: AstNode) {
    if (node.disabled) return;
    if (['Condition', 'Validate', 'Action', 'AsyncAction', 'Transform'].includes(node.kind)) {
      const method = text(node.params.method);
      const condition = node.kind === 'Condition' || node.kind === 'Validate';
      if (handlers.has(method) && handlers.get(method) !== condition)
        throw new Error(`Handler ${method} has conflicting return types.`);
      handlers.set(method, condition);
    }
    node.children.forEach(collect);
  }
  collect(ast.root);
  const add = (s = '') => lines.push(s);
  add(
    `// Generated by Branch Studio. Requires the matching BranchStudio ${workflow ? 'Workflow runtime (.NET 8+ / C# 12)' : 'Game runtime (.NET Standard 2.1 / C# 9)'}.`,
  );
  add('#nullable enable');
  add('using System;');
  add('using System.Collections.Generic;');
  add('using System.Numerics;');
  if (workflow) {
    add('using System.Threading;');
    add('using System.Threading.Tasks;');
  }
  add(`using BranchStudio.${workflow ? 'Workflow' : 'Game'};`);
  add();
  add(`namespace ${ast.settings.namespace}`);
  add('{');
  add(`    public interface ${handlerInterface}`);
  add('    {');
  for (const [method, condition] of handlers) {
    const result = workflow
      ? `global::System.Threading.Tasks.ValueTask<${condition ? 'bool' : statusType}>`
      : condition
        ? 'bool'
        : statusType;
    add(
      `        ${result} ${method}(${workflow ? `${runtime}.WorkflowContext context` : `${runtime}.Blackboard blackboard`}, global::System.Collections.Generic.IReadOnlyList<object?> arguments${workflow ? ', global::System.Threading.CancellationToken cancellationToken' : ''});`,
    );
  }
  add('    }');
  add();
  add(`    public static class ${className}`);
  add('    {');
  add(
    `        public static ${runtime}.${workflow ? 'IWorkflowNode' : 'IBehaviorNode'} Create(${handlerInterface} handlers)`,
  );
  add('        {');
  add(
    '            if (handlers is null) throw new global::System.ArgumentNullException(nameof(handlers));',
  );

  function emit(node: AstNode, indent: number, suffix: string, prefix = '') {
    const pad = ' '.repeat(indent);
    const startLine = lines.length + 1;
    const p = node.params;
    const condition = node.kind === 'Condition' || node.kind === 'Validate';
    const kind = node.kind;
    if (kind === 'Root' && !node.disabled) {
      emit(node.children[0], indent, suffix, prefix);
      ranges[node.id] = { startLine, endLine: lines.length };
      return;
    }
    if (node.disabled)
      add(`${pad}${prefix}new ${runtime}.ConstantNode(${statusType}.Success)${suffix}`);
    else if (['Action', 'AsyncAction', 'Transform', 'Condition', 'Validate'].includes(kind)) {
      const lambda = workflow
        ? `(context, cancellationToken) => handlers.${p.method}(context, ${argumentsLiteral(p.arguments)}, cancellationToken)`
        : `blackboard => handlers.${p.method}(blackboard, ${argumentsLiteral(p.arguments)})`;
      add(
        `${pad}${prefix}new ${runtime}.${condition ? 'ConditionNode' : 'ActionNode'}(${lambda})${suffix}`,
      );
    } else if (['BlackboardCheck', 'SetBlackboard', 'ContextCheck', 'SetContext'].includes(kind)) {
      const variable = ast.variables.find((v) => v.name === p.variable);
      if (!variable) throw new Error(`Undefined variable ${p.variable}.`);
      const type = variable.type;
      const value = literal(text(p.value), type);
      add(
        `${pad}${prefix}new ${runtime}.${kind.endsWith('Check') ? 'VariableCheckNode' : 'SetVariableNode'}<${variableType(type)}>(${quote(variable.name)}, ${value})${suffix}`,
      );
    } else if (kind === 'Wait' || kind === 'Delay')
      add(
        `${pad}${prefix}new ${runtime}.${workflow ? 'Delay' : 'Wait'}Node(global::System.TimeSpan.FromSeconds(${number(p.seconds)}))${suffix}`,
      );
    else if (kind === 'Log')
      add(`${pad}${prefix}new ${runtime}.LogNode(${quote(text(p.message))})${suffix}`);
    else if (kind === 'HttpRequest') {
      const headers = JSON.parse(text(p.headers) || '{}') as Record<string, string>;
      const headerCode = Object.entries(headers)
        .map(([key, value]) => `{ ${quote(key)}, ${quote(value)} }`)
        .join(', ');
      add(
        `${pad}${prefix}new ${runtime}.HttpRequestNode(${quote(text(p.httpMethod))}, ${quote(text(p.url))}, global::System.TimeSpan.FromSeconds(${number(p.timeout, 30)}), new global::System.Collections.Generic.Dictionary<string, string> { ${headerCode} }, ${quote(text(p.credentialEnv))})${suffix}`,
      );
    } else {
      let config = '';
      if (kind === 'Parallel')
        config = `${number(p.successThreshold)}, ${number(p.failureThreshold)}, `;
      if (kind === 'Repeater')
        config = `${number(p.count, 3)}, ${p.untilFailure === true ? 'true' : 'false'}, `;
      if (kind === 'Retry') config = `${number(p.attempts, 3)}, `;
      if (kind === 'Timeout' || kind === 'Cooldown')
        config = `global::System.TimeSpan.FromSeconds(${number(p.seconds)}), `;
      add(`${pad}${prefix}new ${runtime}.${kind}Node(${config}`);
      node.children.forEach((child, i) =>
        emit(child, indent + 4, i === node.children.length - 1 ? '' : ','),
      );
      add(`${pad})${suffix}`);
    }
    ranges[node.id] = { startLine, endLine: lines.length };
  }
  emit(ast.root, 12, ';', 'return ');
  add('        }');
  add();
  const boardType = workflow ? 'WorkflowContext' : 'Blackboard';
  add(
    `        public static ${runtime}.${boardType} Create${boardType}(${workflow ? 'global::System.TimeProvider? timeProvider' : `${runtime}.IGameClock? clock`} = null)`,
  );
  add('        {');
  add(
    `            var ${workflow ? 'context' : 'blackboard'} = new ${runtime}.${boardType}(${workflow ? 'timeProvider: timeProvider' : 'clock: clock'});`,
  );
  for (const v of ast.variables)
    add(
      `            ${workflow ? 'context' : 'blackboard'}.Set<${variableType(v.type)}>(${quote(v.name)}, ${literal(v.value, v.type)});`,
    );
  add(`            return ${workflow ? 'context' : 'blackboard'};`);
  add('        }');
  add('    }');
  add('}');
  return { code: lines.join('\n') + '\n', ranges };
}
