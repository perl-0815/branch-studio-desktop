/** Translate presentation only. IDs, enums, saved user data and generated C# stay untouched. */
export function createTranslator(language: Language): Translator {
  return (message, values) => {
    const translated =
      language === 'ja'
        ? Object.hasOwn(translations, message)
          ? translations[message]
          : (translateDiagnostic(message) ?? message)
        : message;
    return translated.replace(/\{(\w+)\}/g, (placeholder, key: string) =>
      values && Object.hasOwn(values, key) ? String(values[key]) : placeholder,
    );
  };
}
