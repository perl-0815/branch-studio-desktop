using System.Globalization;
using System.Reflection;
using System.Text;
using System.Text.Json;
using BranchStudio.Contracts;

namespace BranchStudio.ContractGen;

internal static class ContractGenerator
{
    private sealed record EnumDefinition(Type Type, string ArrayName, string? Alias = null)
    {
        public FieldInfo[] Fields => Type.GetFields(BindingFlags.Public | BindingFlags.Static)
            .OrderBy(member => member.MetadataToken).ToArray();
        public string[] WireValues => Fields.Select(member => member.GetCustomAttribute<ContractValueAttribute>()?.Value
            ?? throw new InvalidOperationException($"Missing contract value: {Type.Name}.{member.Name}.")).ToArray();
    }

    private static readonly EnumDefinition[] Enums = [
        new(typeof(ProjectMode), "modes", "Mode"),
        new(typeof(NodeKind), "nodeKinds"),
        new(typeof(NodeCategory), "nodeCategories"),
        new(typeof(NodeStatus), "statuses", "Status"),
        new(typeof(WorkflowResult), "workflowResults"),
        new(typeof(VariableType), "variableTypes"),
        new(typeof(ValidationSeverity), "validationSeverities"),
    ];

    private static readonly JsonSerializerOptions JsonOptions = new()
    {
        PropertyNamingPolicy = JsonNamingPolicy.CamelCase,
        WriteIndented = true,
        IndentSize = 2,
        NewLine = "\n",
    };

    internal static IReadOnlyDictionary<string, byte[]> Generate()
    {
        ValidateCatalog();
        var nodes = ContractCatalog.NodeDefinitions.Select(node => new
        {
            kind = ContractValue.GetName(node.Kind),
            node.Label,
            category = ContractValue.GetName(node.Category),
            node.Color,
            node.Description,
            node.Aliases,
            node.MinChildren,
            node.MaxChildren,
            modes = node.Modes.Select(ContractValue.GetName).ToArray(),
            // Defaults(...) declaration order is the canonical Inspector field order.
            defaults = node.Defaults,
        }).ToArray();
        var document = new Dictionary<string, object>(StringComparer.Ordinal)
        {
            ["schemaVersion"] = ContractCatalog.SchemaVersion,
        };
        foreach (var definition in Enums)
            document.Add(definition.ArrayName, definition.WireValues);
        document.Add("nodeDefinitions", nodes);

        var typescript = new StringBuilder("// <auto-generated />\n// Source: src/BranchStudio.Contracts. Regenerate with BranchStudio.ContractGen.\n\n");
        typescript.Append("export const schemaVersion = ").Append(ContractCatalog.SchemaVersion).Append(" as const;\n\n");
        foreach (var definition in Enums)
        {
            typescript.Append("export const ").Append(definition.ArrayName).Append(" = ")
                .Append(JsonSerializer.Serialize(definition.WireValues)).Append(" as const;\n");
            typescript.Append("export type ").Append(definition.Type.Name).Append(" = (typeof ")
                .Append(definition.ArrayName).Append(")[number];\n");
            if (definition.Alias is not null)
                typescript.Append("export type ").Append(definition.Alias).Append(" = ").Append(definition.Type.Name).Append(";\n");
            typescript.Append('\n');
        }
        typescript.Append("""
            export interface GeneratedNodeDefinition {
              kind: NodeKind;
              label: string;
              category: NodeCategory;
              color: string;
              description: string;
              aliases: string;
              minChildren: number;
              /** null means unbounded; the editor adapter converts it to Infinity. */
              maxChildren: number | null;
              modes: Mode[];
              defaults: Record<string, string | number | boolean>;
            }

            export const nodeDefinitions: GeneratedNodeDefinition[] =
            """);
        typescript.Append(' ').Append(JsonSerializer.Serialize(nodes, JsonOptions)).Append(";\n");

        return new Dictionary<string, byte[]>(StringComparer.Ordinal)
        {
            ["contracts.generated.ts"] = Utf8(typescript.ToString()),
            ["contracts.generated.json"] = Utf8(JsonSerializer.Serialize(document, JsonOptions) + "\n"),
            ["contracts.generated.cs"] = Utf8(GenerateCSharp()),
        };
    }

    internal static void ValidateCatalog()
    {
        foreach (var definition in Enums)
        {
            var names = definition.WireValues;
            if (names.Any(string.IsNullOrWhiteSpace) || names.Distinct(StringComparer.Ordinal).Count() != names.Length)
                throw new InvalidOperationException($"Contract values must be nonempty and unique: {definition.Type.Name}.");
        }
        var nodes = ContractCatalog.NodeDefinitions;
        if (!nodes.Select(node => node.Kind).SequenceEqual(ContractCatalog.NodeKinds))
            throw new InvalidOperationException("Define every NodeKind exactly once, in declaration order.");
        foreach (var node in nodes)
        {
            if (string.IsNullOrWhiteSpace(node.Label) || string.IsNullOrWhiteSpace(node.Description)
                || !ContractCatalog.NodeCategories.Contains(node.Category)
                || node.MinChildren < 0 || node.MaxChildren is < 0 || node.MaxChildren < node.MinChildren
                || node.Modes.Count == 0 || node.Modes.Distinct().Count() != node.Modes.Count
                || node.Modes.Any(mode => !ContractCatalog.Modes.Contains(mode)))
                throw new InvalidOperationException($"Invalid metadata for {node.Kind}.");
            foreach (var parameter in node.Defaults)
            {
                if (string.IsNullOrWhiteSpace(parameter.Key)
                    || parameter.Value is not (string or bool or int or double)
                    || parameter.Value is double number && !double.IsFinite(number))
                    throw new InvalidOperationException($"Invalid default {node.Kind}.{parameter.Key}.");
            }
        }
    }

    private static string GenerateCSharp()
    {
        var source = new StringBuilder("// <auto-generated />\n// Source: src/BranchStudio.Contracts. C# 9 / .NET Standard 2.1 compatible.\n\n");
        source.Append("namespace BranchStudio.Contracts\n{\n")
            .Append("    [global::System.AttributeUsage(global::System.AttributeTargets.Field)]\n")
            .Append("    public sealed class ContractValueAttribute : global::System.Attribute\n    {\n")
            .Append("        public ContractValueAttribute(string value) { Value = value; }\n")
            .Append("        public string Value { get; }\n    }\n\n");
        foreach (var definition in Enums)
        {
            source.Append("    public enum ").Append(definition.Type.Name).Append("\n    {\n");
            foreach (var member in definition.Fields)
            {
                var value = member.GetCustomAttribute<ContractValueAttribute>()!.Value;
                source.Append("        [ContractValue(").Append(JsonSerializer.Serialize(value)).Append(")] ")
                    .Append(member.Name).Append(" = ")
                    .Append(Convert.ToInt64(member.GetRawConstantValue(), CultureInfo.InvariantCulture).ToString(CultureInfo.InvariantCulture))
                    .Append(",\n");
            }
            source.Append("    }\n\n");
        }
        return source.Append("}\n").ToString();
    }

    private static byte[] Utf8(string source) => new UTF8Encoding(false, true).GetBytes(source.Replace("\r\n", "\n", StringComparison.Ordinal));
}
